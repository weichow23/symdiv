#!/usr/bin/env python3
import argparse
import json
import statistics
from pathlib import Path
from typing import Any, Dict


def pct(value: float) -> str:
    return "{:.1f}\\%".format(100.0 * value)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--metrics", required=True)
    parser.add_argument("--baseline", required=True)
    parser.add_argument("--neuro")
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    metrics: Dict[str, Any] = json.loads(Path(args.metrics).read_text(encoding="utf-8"))
    baseline: Dict[str, Any] = json.loads(Path(args.baseline).read_text(encoding="utf-8"))
    neuro: Dict[str, Any] = {}
    if args.neuro:
        neuro = json.loads(Path(args.neuro).read_text(encoding="utf-8"))
    rows = []
    for name, values in metrics["systems"].items():
        display = "Clang CSA" if name == "baseline" else "SymDiv"
        rows.append(
            "{} & {} & {} & {} & {} & {} & {} & {} \\\\".format(
                display,
                values["tp"],
                values["fp"],
                values["tn"],
                values["fn"],
                pct(values["precision"]),
                pct(values["recall"]),
                pct(values["f1"]),
            )
        )
    neuro_macros = ""
    if neuro:
        latencies = [
            float(case["client_elapsed_seconds"])
            for case in neuro["cases"]
            if case.get("client_elapsed_seconds") is not None
        ]
        accepted = sum(
            finding["verification"]["status"] == "verified_sat"
            for case in neuro["cases"]
            for finding in case["findings"]
        )
        safe = sum(
            finding["verification"]["status"] == "model_safe"
            for case in neuro["cases"]
            for finding in case["findings"]
        )
        neuro_macros = """\\newcommand{\\NeuroModel}{%s}
\\newcommand{\\NeuroSeconds}{%.3f}
\\newcommand{\\NeuroTokens}{%s}
\\newcommand{\\NeuroInputTokens}{%s}
\\newcommand{\\NeuroOutputTokens}{%s}
\\newcommand{\\NeuroMedianLatency}{%.3f}
\\newcommand{\\NeuroAccepted}{%s}
\\newcommand{\\NeuroSafe}{%s}
""" % (
            str(neuro["model"]).replace("_", "\\_"),
            neuro["elapsed_seconds"],
            f'{neuro["total_tokens"]:,}',
            f'{sum(int(case.get("input_tokens") or 0) for case in neuro["cases"]):,}',
            f'{sum(int(case.get("output_tokens") or 0) for case in neuro["cases"]):,}',
            statistics.median(latencies),
            accepted,
            safe,
        )
    content = """%% Generated by scripts/render_results.py; do not edit.
\\newcommand{\\BaselineVersion}{%s}
\\newcommand{\\BaselineSeconds}{%.3f}
%s
\\begin{table}[t]
  \\caption{Pilot classification results from 24 balanced C11 subjects.}
  \\label{tab:pilot-results}
  \\centering
  \\small
  \\begin{tabular}{lrrrrrrr}
    \\toprule
    System & TP & FP & TN & FN & Prec. & Recall & F1 \\\\
    \\midrule
%s
    \\bottomrule
  \\end{tabular}
\\end{table}
""" % (
        baseline["tool_version"].replace("_", "\\_"),
        baseline["elapsed_seconds"],
        neuro_macros.rstrip(),
        "\n".join("    " + row for row in rows),
    )
    output = Path(args.out)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
